def resolve_theme(name: str, overrides: dict[str, str] | None = None) -> ThemePalette:
    """Resolve a built-in theme by name and apply optional hex overrides."""
    base = THEMES.get(name, THEMES["chesscom-green"])
    if not overrides:
        return base
    data = {field: getattr(base, field) for field in base.__dataclass_fields__}
    for key, value in overrides.items():
        if key in data and isinstance(value, str) and value.strip():
            data[key] = value.strip()
    return ThemePalette(**data)
